package com.example.lazypc.security

/** JNI facade for the shared Rust `snow` Noise implementation. */
internal class SecureLinkNoiseNative {
    companion object {
        init {
            System.loadLibrary("lazypc_noise")
        }
    }

    external fun nativeGenerateStaticKeyPair(): ByteArray
    external fun nativeCreateInitiator(
        localPrivate: ByteArray,
        remotePublic: ByteArray,
        psk: ByteArray
    ): Long
    external fun nativeWriteMessage(handle: Long, payload: ByteArray): ByteArray
    external fun nativeReadMessage(handle: Long, message: ByteArray): ByteArray
    external fun nativeHandshakeHash(handle: Long): ByteArray
    external fun nativeIsHandshakeFinished(handle: Long): Boolean
    external fun nativeDestroy(handle: Long)
}

/** Owns one Rust Noise state machine; always close it when the attempt ends. */
class SecureLinkNoiseSession private constructor(
    private val native: SecureLinkNoiseNative,
    private var handle: Long
) : AutoCloseable {
    val isHandshakeFinished: Boolean
        get() = requireHandle().let(native::nativeIsHandshakeFinished)

    fun writeMessage(payload: ByteArray): ByteArray =
        native.nativeWriteMessage(requireHandle(), payload)

    fun readMessage(message: ByteArray): ByteArray =
        native.nativeReadMessage(requireHandle(), message)

    fun handshakeHash(): ByteArray =
        native.nativeHandshakeHash(requireHandle())

    private fun requireHandle(): Long {
        check(handle != 0L) { "Noise session is closed" }
        return handle
    }

    override fun close() {
        val current = handle
        handle = 0L
        if (current != 0L) native.nativeDestroy(current)
    }

    companion object {
        data class StaticKeyPair(val privateKey: ByteArray, val publicKey: ByteArray)

        /** Returns a 32-byte X25519 private/public pair generated by Rust `snow`. */
        fun generateStaticKeyPair(): StaticKeyPair {
            val raw = SecureLinkNoiseNative().nativeGenerateStaticKeyPair()
            require(raw.size == 64) { "Unexpected Rust Noise key-pair length" }
            return try {
                StaticKeyPair(raw.copyOfRange(0, 32), raw.copyOfRange(32, 64))
            } finally {
                raw.fill(0)
            }
        }

        /** Pairing uses Noise_IKpsk2_25519_ChaChaPoly_SHA256 when PSK is non-empty. */
        fun pairingInitiator(
            localPrivateKey: ByteArray,
            pcStaticPublicKey: ByteArray,
            psk: ByteArray
        ): SecureLinkNoiseSession {
            require(localPrivateKey.size == 32) { "Phone static private key must be 32 bytes" }
            require(pcStaticPublicKey.size == 32) { "PC static public key must be 32 bytes" }
            require(psk.size == 32) { "Pairing PSK must be 32 bytes" }
            return create(localPrivateKey, pcStaticPublicKey, psk)
        }

        /** Normal trusted sessions use Noise_IK_25519_ChaChaPoly_SHA256 (no PSK). */
        fun sessionInitiator(
            localPrivateKey: ByteArray,
            pcStaticPublicKey: ByteArray
        ): SecureLinkNoiseSession {
            require(localPrivateKey.size == 32) { "Phone static private key must be 32 bytes" }
            require(pcStaticPublicKey.size == 32) { "PC static public key must be 32 bytes" }
            return create(localPrivateKey, pcStaticPublicKey, byteArrayOf())
        }

        private fun create(privateKey: ByteArray, remotePublicKey: ByteArray, psk: ByteArray): SecureLinkNoiseSession {
            val native = SecureLinkNoiseNative()
            val handle = native.nativeCreateInitiator(privateKey, remotePublicKey, psk)
            check(handle != 0L) { "Rust Noise session creation failed" }
            return SecureLinkNoiseSession(native, handle)
        }
    }
}
